# Расчет площади прямоугольника
# Запрос пользователю на ввод длины
length = int(input("Введите длину прямоугольника:"))
# Запрос пользователю на ввод ширины
width = int(input("Введите ширину прямоугольника:"))
area = width*length
# Вывод сообщения с рассчитанной площадью
print(f"Площадь прямоугольника равна: {area}")
